#!/usr/bin/env python3
"""Write hash-locked requirement files for this platform (0.10.6, SEC-002): every package Asistent installs, the direct
pins and everything they pull in, at one version each, with the SHA-256 of every file PyPI has for that version.

  lock_requirements.py            -> requirements-lock-<platform>.txt and requirements-asr-lock-<platform>.txt

pip resolves the requirement files without installing anything (--dry-run --report); the hashes come from PyPI's JSON. The
setup script installs from the lock with --require-hashes, so a changed or substituted file is refused. Run it again after
changing a requirements file (on each platform: the resolution differs between Mac and Windows).
"""
import json
import os
import subprocess
import sys
import tempfile
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLATFORM = {"darwin": "mac", "win32": "win"}.get(sys.platform, sys.platform)


def resolve(req: str) -> list[tuple[str, str]]:
    """The packages pip would install for `req`, preferring the versions installed in the Python running this script (the
    ones Asistent was tested with): those are passed as constraints."""
    with tempfile.TemporaryDirectory() as d:
        report = os.path.join(d, "report.json")
        tested = os.path.join(d, "tested.txt")
        freeze = subprocess.run([sys.executable, "-m", "pip", "freeze", "--exclude-editable"], capture_output=True, text=True, check=True)
        with open(tested, "w", encoding="utf-8") as f:
            f.write(freeze.stdout)
        subprocess.run([sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet", "--report", report,
                        "-c", tested, "-r", os.path.join(REPO, req)], check=True)
        with open(report, encoding="utf-8") as f:
            data = json.load(f)
    return sorted({(i["metadata"]["name"].lower().replace("_", "-"), i["metadata"]["version"]) for i in data["install"]})


def hashes(name: str, version: str) -> list[str]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as r:
        data = json.load(r)
    return sorted({f["digests"]["sha256"] for f in data["urls"]})


def write(req: str, out: str) -> None:
    lines = [f"# Generated by scripts/lock_requirements.py from {req} on {PLATFORM}: do not edit by hand.",
             "# Installed with: pip install --require-hashes -r " + out]
    for name, version in resolve(req):
        hs = hashes(name, version)
        lines.append(f"{name}=={version} \\")
        lines += [f"    --hash=sha256:{h} \\" for h in hs[:-1]] + [f"    --hash=sha256:{hs[-1]}"]
    with open(os.path.join(REPO, out), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{out}: {sum(1 for l in lines if '==' in l)} packages")


if __name__ == "__main__":
    write("requirements.txt", f"requirements-lock-{PLATFORM}.txt")
    write("requirements-asr.txt", f"requirements-asr-lock-{PLATFORM}.txt")
